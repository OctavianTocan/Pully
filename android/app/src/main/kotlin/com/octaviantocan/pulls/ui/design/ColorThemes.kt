package com.octaviantocan.pulls.ui.design

import androidx.compose.runtime.Immutable
import androidx.compose.runtime.staticCompositionLocalOf

/**
 * A colour theme (K18): a whole palette for each look. The Light, Dark and System choice still picks the look; the
 * theme picks the palette it is drawn in. [dark] is null for a theme with one look, which is then used for both, so a
 * dark-only theme stays dark when Light is chosen ([PullsColors.dark] says which look a palette really is).
 */
@Immutable
data class ColorTheme(
    /** What Settings stores: `pulls`, or the OpenCode theme's own name (`tokyonight`). */
    val id: String,
    /** The name shown in the picker, never translated. */
    val name: String,
    val light: PullsColors,
    val dark: PullsColors? = null,
) {
    /** The palette for the look the Light, Dark and System choice asked for. */
    fun colors(dark: Boolean): PullsColors = if (dark) this.dark ?: light else light
}

/**
 * Every theme the app can be drawn in: Pulls' own palette first, the default, then the themes converted from
 * OpenCode's ([OpenCodeThemes], generated by `android/scripts/gen-opencode-themes.mjs`).
 */
object ColorThemes {
    const val DEFAULT = "pulls"

    val Pulls = ColorTheme(DEFAULT, "Pulls", LightPullsColors, DarkPullsColors)

    val all: List<ColorTheme> = listOf(Pulls) + OpenCodeThemes

    /** The theme stored as [id], or Pulls when there is none by that name (a theme that was dropped since). */
    fun of(id: String?): ColorTheme = all.firstOrNull { it.id == id } ?: Pulls
}

/** The theme the app is drawn in, so a preview can show another look of the same theme (the UI Book's frames). */
val LocalColorTheme = staticCompositionLocalOf { ColorThemes.Pulls }

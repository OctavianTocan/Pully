// Generates res/drawable/ic_cat_*.xml from @iconify-json/catppuccin, in the icons' own
// colors, for every icon `getFileIcon` (@antfu/design/utils/icon.ts) can pick plus the
// folder glyphs. Run from the repo root:
//   node android/scripts/gen-catppuccin.mjs
import { readdirSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { join } from 'node:path'

const require = createRequire(import.meta.url)
const root = new URL('../../', import.meta.url).pathname
function iconsJson() {
  const base = join(root, 'node_modules/.pnpm')
  const dir = readdirSync(base).find(d => d.startsWith('@iconify-json+catppuccin@'))
  return join(base, dir, 'node_modules/@iconify-json/catppuccin/icons.json')
}

const set = require(iconsJson())
const out = join(root, 'android/app/src/main/res/drawable')

const NAMES = [
  'vue',
  'typescript-react',
  'javascript-react',
  'typescript-def',
  'typescript',
  'javascript',
  'json',
  'yaml',
  'toml',
  'markdown',
  'html',
  'css',
  'sass',
  'svg',
  'image',
  'font',
  'webassembly',
  'npm',
  'typescript-test',
  'file',
  'folder',
  'folder-open',
]

function attr(tag, name) {
  return new RegExp(`\\b${name}="([^"]*)"`).exec(tag)?.[1]
}

function color(value) {
  if (!value || value === 'none')
    return undefined
  if (value === 'currentColor')
    return '#FFCAD3F5'
  const hex = value.replace('#', '')
  const full = hex.length === 3 ? hex.split('').map(ch => ch + ch).join('') : hex
  return `#FF${full.toUpperCase()}`
}

function circlePath(cx, cy, r) {
  return `M${cx - r},${cy}a${r},${r} 0 1,0 ${r * 2},0a${r},${r} 0 1,0 ${-r * 2},0`
}

function body(name) {
  const icon = set.icons[name]
  if (icon)
    return icon.body
  const alias = set.aliases?.[name]
  return alias ? body(alias.parent) : undefined
}

let written = 0
for (const name of NAMES) {
  const svg = body(name)
  if (!svg) {
    console.warn(`missing ${name}`)
    continue
  }
  const paths = []
  // Walk tags in order, keeping the attributes inherited from enclosing `<g>`s.
  const stack = [{}]
  for (const match of svg.matchAll(/<(\/?)(g|path|circle|rect)\b([^>]*?)(\/?)>/g)) {
    const [, closing, tag, attrs, selfClosing] = match
    if (tag === 'g') {
      if (closing)
        stack.pop()
      else
        stack.push({ ...stack.at(-1), ...Object.fromEntries(['fill', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin', 'opacity'].map(k => [k, attr(attrs, k)]).filter(([, v]) => v !== undefined)) })
      continue
    }
    if (closing)
      continue
    const inherited = stack.at(-1)
    const get = k => attr(attrs, k) ?? inherited[k]
    let d = attr(attrs, 'd')
    if (tag === 'circle')
      d = circlePath(Number(attr(attrs, 'cx')), Number(attr(attrs, 'cy')), Number(attr(attrs, 'r')))
    if (tag === 'rect') {
      const x = Number(attr(attrs, 'x') ?? 0)
      const y = Number(attr(attrs, 'y') ?? 0)
      const w = Number(attr(attrs, 'width'))
      const h = Number(attr(attrs, 'height'))
      d = `M${x},${y}h${w}v${h}h${-w}z`
    }
    if (!d)
      continue
    const fill = color(get('fill') ?? (get('stroke') ? 'none' : '#cad3f5'))
    const stroke = color(get('stroke'))
    const lines = [`        android:pathData="${d}"`, `        android:fillColor="${fill ?? '#00000000'}"`]
    if (stroke) {
      lines.push(`        android:strokeColor="${stroke}"`, `        android:strokeWidth="${get('stroke-width') ?? 1}"`)
      lines.push(`        android:strokeLineCap="${get('stroke-linecap') ?? 'butt'}"`, `        android:strokeLineJoin="${get('stroke-linejoin') ?? 'miter'}"`)
    }
    const opacity = get('opacity')
    if (opacity)
      lines.push(fill ? `        android:fillAlpha="${opacity}"` : `        android:strokeAlpha="${opacity}"`)
    paths.push(`    <path\n${lines.join('\n')} />`)
    void selfClosing
  }
  const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by android/scripts/gen-catppuccin.mjs from @iconify-json/catppuccin "${name}". -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="16dp"
    android:height="16dp"
    android:viewportWidth="${set.icons[name]?.width ?? set.width ?? 16}"
    android:viewportHeight="${set.icons[name]?.height ?? set.height ?? 16}">
${paths.join('\n')}
</vector>
`
  writeFileSync(join(out, `ic_cat_${name.replace(/-/g, '_')}.xml`), xml)
  written++
}
console.log(`wrote ${written} Catppuccin icons`)

// Generates res/drawable/ic_ph_*.xml from @iconify-json/ph for every Phosphor icon
// the web app uses (`i-ph:<name>` / `i-ph-<name>` in packages/app/src), so the phone
// draws the same glyphs. Run from the repo root:
//   node android/scripts/gen-phosphor.mjs
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { join } from 'node:path'

const require = createRequire(import.meta.url)
const root = new URL('../../', import.meta.url).pathname
const set = require(join(root, 'node_modules/@iconify-json/ph/icons.json'))
const out = join(root, 'android/app/src/main/res/drawable')

function walk(dir, files = []) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name)
    if (statSync(path).isDirectory())
      walk(path, files)
    else if (/\.(?:vue|ts)$/.test(name))
      files.push(path)
  }
  return files
}

const used = new Set()
for (const file of walk(join(root, 'packages/app/src'))) {
  for (const match of readFileSync(file, 'utf8').matchAll(/i-ph[:-]([a-z0-9-]+)/g))
    used.add(match[1])
}
// Icons only the phone needs (its own chrome around the same features).
for (const extra of ['arrow-left', 'dots-three-vertical', 'gear-six-duotone', 'columns-duotone', 'rows-duotone', 'plus', 'magnifying-glass-duotone', 'x', 'chat-circle-dots-duotone', 'sparkle-duotone', 'link', 'arrow-square-out', 'file-text-duotone', 'caret-down', 'caret-right', 'check', 'copy', 'tree-structure-duotone', 'list-duotone', 'paper-plane-tilt-duotone', 'stop-duotone'])
  used.add(extra)

function body(name) {
  const icon = set.icons[name]
  if (icon)
    return icon.body
  const alias = set.aliases?.[name]
  return alias ? body(alias.parent) : undefined
}

let written = 0
for (const name of [...used].sort()) {
  const svg = body(name)
  if (!svg) {
    console.warn(`missing ${name}`)
    continue
  }
  const paths = []
  // Groups in Phosphor only carry `fill="currentColor"`; opacity sits on the paths.
  for (const match of svg.matchAll(/<path([^>]*)\/?>/g)) {
    const attrs = match[1]
    const d = /\bd="([^"]+)"/.exec(attrs)?.[1]
    if (!d)
      continue
    const opacity = /\bopacity="([^"]+)"/.exec(attrs)?.[1]
    const rule = /fill-rule="evenodd"/.test(attrs) ? '\n        android:fillType="evenOdd"' : ''
    paths.push(`    <path\n        android:pathData="${d}"\n        android:fillColor="#FFFFFFFF"${opacity ? `\n        android:fillAlpha="${opacity}"` : ''}${rule} />`)
  }
  const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by android/scripts/gen-phosphor.mjs from @iconify-json/ph "${name}". -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="${set.width ?? 256}"
    android:viewportHeight="${set.height ?? 256}">
${paths.join('\n')}
</vector>
`
  writeFileSync(join(out, `ic_ph_${name.replace(/-/g, '_')}.xml`), xml)
  written++
}
console.log(`wrote ${written} Phosphor icons`)
